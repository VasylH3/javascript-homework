// 'number' + 3 + 3
// 'number' + 3 → конкатенація → 'number3'
// 'number3' + 3 → знову конкатенація → 'number33'
// Результат: 'number33'

// null + 3
// null → 0 (автоматичне приведення до числа)
// 0 + 3 = 3
// Результат: 3

// 5 && "qwerty"
// 5 — truthy → перевіряємо далі
// "qwerty" — також truthy → повертається останнє: "qwerty"
// Результат: "qwerty"

// +'40' + +'2' + "hillel"
// +'40' → 40 (унарний плюс: рядок у число)
// +'2' → 2
// 40 + 2 = 42
// 42 + "hillel" → число + рядок = конкатенація → "42hillel"
// Результат: "42hillel"

// '10' - 5 === 6
// '10' → 10 (рядок у число)
// 10 - 5 = 5
// 5 === 6 → false
// Результат: false

// true + false
// true → 1, false → 0
// 1 + 0 = 1
// Результат: 1

// '4px' - 3
// '4px' → NaN (не можна перетворити у число)
// NaN - 3 = NaN
// Результат: NaN

// '4' - 3
// '4' → 4 (рядок у число)
// 4 - 3 = 1
// Результат: 1

// '6' + 3 ** 0
// 3 ** 0 = 1
// '6' + 1 → рядок + число = "61"
// Результат: "61"

// 12 / '6'
// '6' → 6 (рядок у число)
// 12 / 6 = 2
// Результат: 2

// '10' + (5 === 6)
// 5 === 6 → false
// '10' + false → рядок + булеве → конкатенація: "10false"
// Результат: "10false"

// null == ''
// null == undefined → true
// null == '' → false (різні типи)
// Результат: false

// 3 ** (9 / 3)
// 9 / 3 = 3
// 3 ** 3 = 27
// Результат: 27

// !!'false' == !!'true'
// 'false' → true, 'true' → true (непорожні рядки → truthy)
// !!'false' → true, !!'true' → true
// true == true → true
// Результат: true

// 0 || '0' && 1
// '0' && 1 → 1 (обидва truthy → повертається 1)
// 0 || 1 → 1
// Результат: 1

// (+null == false) < 1
// +null → 0, false → 0
// 0 == 0 → true
// true → 1 → 1 < 1 → false
// Але насправді: true < 1 → false (бо true → 1)
// Результат: false

// false && true || true
// false && true → false
// false || true → true
// Результат: true

// false && (false || true)
// (false || true) → true
// false && true → false
// Результат: false

// (+null == false) < 1 ** 5
// +null → 0, false → 0
// 0 == 0 → true
// 1 ** 5 = 1 → true < 1 → false
// Результат: false

